// createCompany is a test helper that inserts a company and fails the test on error.
func createCompany(t *testing.T, repo *CompanyRepository, name, dot string) *model.Company {
	t.Helper()
	c, err := repo.Create(context.Background(), model.Company{
		Name: name, DOTNumber: dot, Timezone: "America/Chicago", HOSCycle: model.HOSCycle70in8,
	})
	require.NoError(t, err)
	return c
}

func TestCompanyRepository_Create(t *testing.T) {
	repo := NewCompanyRepository(newTestDB(t))

	c, err := repo.Create(context.Background(), model.Company{
		Name: "Acme Freight", DOTNumber: "1234567", Timezone: "America/Chicago", HOSCycle: model.HOSCycle70in8,
	})

	require.NoError(t, err)
	assert.NotEqual(t, uuid.Nil, c.ID, "id is generated by the database")
	assert.Equal(t, byte(7), byte(c.ID.Version()), "id must be UUIDv7")
	assert.Equal(t, "Acme Freight", c.Name)
	assert.Equal(t, "1234567", c.DOTNumber)
	assert.Equal(t, "America/Chicago", c.Timezone)
	assert.Equal(t, model.HOSCycle70in8, c.HOSCycle)
	assert.True(t, c.IsActive, "new companies are active by default")
	assert.False(t, c.CreatedAt.IsZero())
	assert.Nil(t, c.DeletedAt)
}

func TestCompanyRepository_Create_DuplicateDOT(t *testing.T) {
	repo := NewCompanyRepository(newTestDB(t))
	createCompany(t, repo, "Acme", "1234567")

	_, err := repo.Create(context.Background(), model.Company{
		Name: "Copycat", DOTNumber: "1234567", Timezone: "America/Chicago", HOSCycle: model.HOSCycle70in8,
	})

	assert.ErrorIs(t, err, model.ErrDOTNumberTaken)
}

func TestCompanyRepository_GetByID(t *testing.T) {
	repo := NewCompanyRepository(newTestDB(t))
	ctx := context.Background()
	created := createCompany(t, repo, "Acme", "1234567")

	t.Run("found", func(t *testing.T) {
		got, err := repo.GetByID(ctx, created.ID)

		require.NoError(t, err)
		assert.Equal(t, created.ID, got.ID)
		assert.Equal(t, created.Name, got.Name)
	})

	t.Run("unknown id", func(t *testing.T) {
		_, err := repo.GetByID(ctx, uuid.New())

		assert.ErrorIs(t, err, model.ErrNotFound)
	})

	t.Run("soft-deleted is hidden", func(t *testing.T) {
		require.NoError(t, repo.SoftDelete(ctx, created.ID))

		_, err := repo.GetByID(ctx, created.ID)

		assert.ErrorIs(t, err, model.ErrNotFound)
	})
}

func TestCompanyRepository_List(t *testing.T) {
	repo := NewCompanyRepository(newTestDB(t))
	ctx := context.Background()
	a := createCompany(t, repo, "A", "1")
	b := createCompany(t, repo, "B", "2")
	c := createCompany(t, repo, "C", "3")
	deleted := createCompany(t, repo, "Deleted", "4")
	require.NoError(t, repo.SoftDelete(ctx, deleted.ID))

	t.Run("first page", func(t *testing.T) {
		page, total, err := repo.List(ctx, model.CompanyFilter{}, 2, 0)

		require.NoError(t, err)
		assert.Equal(t, 3, total, "deleted companies are not counted")
		require.Len(t, page, 2)
		assert.Equal(t, a.ID, page[0].ID, "ordered by creation (UUIDv7)")
		assert.Equal(t, b.ID, page[1].ID)
	})

	t.Run("second page", func(t *testing.T) {
		page, total, err := repo.List(ctx, model.CompanyFilter{}, 2, 2)

		require.NoError(t, err)
		assert.Equal(t, 3, total)
		require.Len(t, page, 1)
		assert.Equal(t, c.ID, page[0].ID)
	})

	t.Run("past the end", func(t *testing.T) {
		page, total, err := repo.List(ctx, model.CompanyFilter{}, 2, 10)

		require.NoError(t, err)
		assert.Equal(t, 3, total)
		assert.Empty(t, page)
	})
}

func TestCompanyRepository_Update(t *testing.T) {
	repo := NewCompanyRepository(newTestDB(t))
	ctx := context.Background()
	acme := createCompany(t, repo, "Acme", "1111")
	other := createCompany(t, repo, "Other", "2222")

	t.Run("updates editable fields", func(t *testing.T) {
		changed := *acme
		changed.Name = "Acme LLC"
		changed.Timezone = "America/New_York"
		changed.IsActive = false

		got, err := repo.Update(ctx, changed)

		require.NoError(t, err)
		assert.Equal(t, "Acme LLC", got.Name)
		assert.Equal(t, "America/New_York", got.Timezone)
		assert.False(t, got.IsActive)
		assert.Equal(t, acme.CreatedAt, got.CreatedAt, "created_at never changes")
		assert.True(t, got.UpdatedAt.After(acme.UpdatedAt), "trigger bumps updated_at")
	})

	t.Run("duplicate DOT", func(t *testing.T) {
		changed := *acme
		changed.DOTNumber = other.DOTNumber

		_, err := repo.Update(ctx, changed)

		assert.ErrorIs(t, err, model.ErrDOTNumberTaken)
	})

	t.Run("unknown id", func(t *testing.T) {
		_, err := repo.Update(ctx, model.Company{
			ID: uuid.New(), Name: "X", DOTNumber: "9", Timezone: "UTC",
		})

		assert.ErrorIs(t, err, model.ErrNotFound)
	})
}

func TestCompanyRepository_SoftDelete(t *testing.T) {
	repo := NewCompanyRepository(newTestDB(t))
	ctx := context.Background()
	acme := createCompany(t, repo, "Acme", "1234567")

	require.NoError(t, repo.SoftDelete(ctx, acme.ID))

	t.Run("second delete is not found", func(t *testing.T) {
		assert.ErrorIs(t, repo.SoftDelete(ctx, acme.ID), model.ErrNotFound)
	})

	t.Run("unknown id is not found", func(t *testing.T) {
		assert.ErrorIs(t, repo.SoftDelete(ctx, uuid.New()), model.ErrNotFound)
	})

	t.Run("dot number can be reused", func(t *testing.T) {
		reborn := createCompany(t, repo, "Acme Reborn", "1234567")

		assert.NotEqual(t, acme.ID, reborn.ID)
	})
}

