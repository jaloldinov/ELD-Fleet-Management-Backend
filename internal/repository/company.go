package repository

import (
	"context"
	"errors"
	"fmt"

	"github.com/google/uuid"
	"github.com/jackc/pgx/v5"

	"github.com/jaloldinov/ELD-learning/internal/model"
)

// companyColumns is shared by every SELECT/RETURNING so the column order always
// matches scanCompany.
const companyColumns = `id, name, dot_number, timezone, is_active, stripe_customer_id, billing_status, created_at, updated_at, deleted_at`

type CompanyRepository struct {
	db DBTX
}

func NewCompanyRepository(db DBTX) *CompanyRepository {
	return &CompanyRepository{db: db}
}

// q returns the connection to use: the caller's transaction if ctx carries
// one, otherwise the pool.
func (r *CompanyRepository) q(ctx context.Context) DBTX {
	return conn(ctx, r.db)
}

// Create inserts a company. ID, IsActive and timestamps are generated by the
// database and returned in the result.
func (r *CompanyRepository) Create(ctx context.Context, c model.Company) (*model.Company, error) {
	// $1, $2, ... are placeholders. Values are sent separately from the SQL
	// text, so SQL injection is impossible. Never build SQL with fmt.Sprintf
	// from user input.
	row := r.q(ctx).QueryRow(ctx, `
		INSERT INTO companies (name, dot_number, timezone)
		VALUES ($1, $2, $3)
		RETURNING `+companyColumns,
		c.Name, c.DOTNumber, c.Timezone,
	)

	created, err := scanCompany(row)
	if err != nil {
		return nil, mapCompanyError("create company", err)
	}
	return created, nil
}

// GetByID returns an alive (not soft-deleted) company or model.ErrNotFound.
func (r *CompanyRepository) GetByID(ctx context.Context, id uuid.UUID) (*model.Company, error) {
	row := r.q(ctx).QueryRow(ctx, `
		SELECT `+companyColumns+`
		FROM companies
		WHERE id = $1 AND deleted_at IS NULL`,
		id,
	)

	c, err := scanCompany(row)
	if err != nil {
		return nil, mapCompanyError("get company", err)
	}
	return c, nil
}

// List returns one page of alive companies (oldest first) and the total count.
func (r *CompanyRepository) List(ctx context.Context, f model.CompanyFilter, limit, offset int) ([]model.Company, int, error) {
	// "$1::uuid IS NULL OR id = $1": one query handles both cases. When the
	// filter is nil the condition is always true; otherwise only that id.
	// The ::uuid cast tells Postgres the type of a NULL parameter.
	var total int
	if err := r.q(ctx).QueryRow(ctx, `
		SELECT count(*) FROM companies
		WHERE deleted_at IS NULL AND ($1::uuid IS NULL OR id = $1)`,
		f.OnlyID,
	).Scan(&total); err != nil {
		return nil, 0, fmt.Errorf("count companies: %w", err)
	}

	// ORDER BY id works as "creation order" because ids are UUIDv7.
	// A stable ORDER BY is required for paging: without it Postgres may
	// return rows in a different order on each call.
	rows, err := r.q(ctx).Query(ctx, `
		SELECT `+companyColumns+`
		FROM companies
		WHERE deleted_at IS NULL AND ($1::uuid IS NULL OR id = $1)
		ORDER BY id
		LIMIT $2 OFFSET $3`,
		f.OnlyID, limit, offset,
	)
	if err != nil {
		return nil, 0, fmt.Errorf("list companies: %w", err)
	}
	// CollectRows reads every row with scanCompany and always closes rows.
	companies, err := pgx.CollectRows(rows, func(row pgx.CollectableRow) (model.Company, error) {
		c, err := scanCompany(row)
		if err != nil {
			return model.Company{}, err
		}
		return *c, nil
	})
	if err != nil {
		return nil, 0, fmt.Errorf("scan companies: %w", err)
	}

	return companies, total, nil
}

// Update overwrites the editable fields of an alive company.
// The service does "read → apply changes → Update", so all fields are sent.
func (r *CompanyRepository) Update(ctx context.Context, c model.Company) (*model.Company, error) {
	row := r.q(ctx).QueryRow(ctx, `
		UPDATE companies
		SET name = $2, dot_number = $3, timezone = $4, is_active = $5
		WHERE id = $1 AND deleted_at IS NULL
		RETURNING `+companyColumns,
		c.ID, c.Name, c.DOTNumber, c.Timezone, c.IsActive,
	)

	updated, err := scanCompany(row)
	if err != nil {
		return nil, mapCompanyError("update company", err)
	}
	return updated, nil
}

// SoftDelete marks a company as deleted. Deleting an already deleted or
// unknown company returns model.ErrNotFound.
func (r *CompanyRepository) SoftDelete(ctx context.Context, id uuid.UUID) error {
	tag, err := r.q(ctx).Exec(ctx, `
		UPDATE companies
		SET deleted_at = now()
		WHERE id = $1 AND deleted_at IS NULL`,
		id,
	)
	if err != nil {
		return fmt.Errorf("delete company: %w", err)
	}
	// Exec does not return pgx.ErrNoRows; we check how many rows changed.
	if tag.RowsAffected() == 0 {
		return model.ErrNotFound
	}
	return nil
}

// SetStripeCustomerID links the company to its Stripe Customer, only if it
// has none yet, and returns the id that is linked afterwards. When two
// requests race, both get the same answer: the first one saved wins.
func (r *CompanyRepository) SetStripeCustomerID(ctx context.Context, id uuid.UUID, customerID string) (string, error) {
	var linked string
	err := r.q(ctx).QueryRow(ctx, `
		UPDATE companies
		SET stripe_customer_id = COALESCE(stripe_customer_id, $2)
		WHERE id = $1 AND deleted_at IS NULL
		RETURNING stripe_customer_id`,
		id, customerID,
	).Scan(&linked)
	if err != nil {
		return "", mapCompanyError("set stripe customer", err)
	}
	return linked, nil
}

// GetByStripeCustomerID finds the company of a Stripe Customer (cus_...),
// deleted companies included: their old subscriptions still send events.
func (r *CompanyRepository) GetByStripeCustomerID(ctx context.Context, customerID string) (*model.Company, error) {
	row := r.q(ctx).QueryRow(ctx, `
		SELECT `+companyColumns+` FROM companies WHERE stripe_customer_id = $1`, customerID)
	c, err := scanCompany(row)
	if err != nil {
		return nil, mapCompanyError("get company by stripe customer", err)
	}
	return c, nil
}

// SetBillingStatus saves the company's billing status and returns the one
// it had before (the row is locked, so the "before" is exact even when two
// syncs race).
func (r *CompanyRepository) SetBillingStatus(ctx context.Context, id uuid.UUID, status string) (old string, err error) {
	err = r.q(ctx).QueryRow(ctx, `
		WITH before AS (
			SELECT billing_status FROM companies WHERE id = $1 FOR UPDATE
		)
		UPDATE companies SET billing_status = $2
		FROM before
		WHERE companies.id = $1
		RETURNING before.billing_status`,
		id, status,
	).Scan(&old)
	if err != nil {
		return "", mapCompanyError("set billing status", err)
	}
	return old, nil
}

// BillingStatus returns only the company's billing status: the cheap
// lookup done on every request to a fleet route.
func (r *CompanyRepository) BillingStatus(ctx context.Context, id uuid.UUID) (string, error) {
	var status string
	err := r.q(ctx).QueryRow(ctx, `
		SELECT billing_status FROM companies WHERE id = $1 AND deleted_at IS NULL`, id).Scan(&status)
	if err != nil {
		return "", mapCompanyError("get billing status", err)
	}
	return status, nil
}

// scanCompany reads one row in companyColumns order.
// pgx.Row is satisfied by both QueryRow's result and rows inside CollectRows.
func scanCompany(row pgx.Row) (*model.Company, error) {
	var c model.Company
	err := row.Scan(
		&c.ID, &c.Name, &c.DOTNumber, &c.Timezone, &c.IsActive, &c.StripeCustomerID, &c.BillingStatus,
		&c.CreatedAt, &c.UpdatedAt, &c.DeletedAt,
	)
	if err != nil {
		return nil, err
	}
	return &c, nil
}

// mapCompanyError translates database errors into domain errors.
// Unknown errors are wrapped with context and returned as-is (they become 500s).
func mapCompanyError(op string, err error) error {
	if errors.Is(err, pgx.ErrNoRows) {
		return model.ErrNotFound
	}

	if isUniqueViolation(err, "companies_dot_number_alive_uniq") {
		return model.ErrDOTNumberTaken
	}

	return fmt.Errorf("%s: %w", op, err)
}
